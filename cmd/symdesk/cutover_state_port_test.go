// RUST-018 cutover-state recorder. The stable release ships Rust only, so the
// evidence that a Rust binary opens state a Go binary created must replay
// without Go. This test builds the real Go symdesk and symroom, creates
// realistic state (vault, sidecar and retrieval indexes, an ingested document,
// contacts, saved views, a signed room journal) in a disposable root at ONE
// fixed absolute path (the sidecar and retrieval databases embed absolute
// vault paths and vault-hash directory names), and freezes the resulting tree
// as a compressed archive plus a manifest of file digests and the Go outputs
// of read-only queries. The Rust replays (crates/symdesk-cli/tests/
// cutover_state.rs, crates/symroom-cli/tests/cutover_state.rs) unpack it at the
// same path and need no Go.
//
//	generate: make cutover-state-fixtures-generate  (records this host's OS)
//	check:    make cutover-state-differential       (Go re-runs the frozen
//	          queries against the committed tree; the Rust replay follows)
//
// The recording is not byte-reproducible (ids, key material and timestamps are
// random), so check mode compares behaviour, never regenerated bytes.

