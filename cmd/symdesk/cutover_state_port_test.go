func cutoverRecordStates(t *testing.T) cutoverManifest {
	t.Helper()
	root := cutoverCanonicalRoot(t)
	if err := os.RemoveAll(root); err != nil {
		t.Fatal(err)
	}
	for _, directory := range []string{"home", "vault/notes", "vault/bases", "cwd", "room", "inbox"} {
		if err := os.MkdirAll(filepath.Join(root, directory), 0o755); err != nil { //nolint:gosec // disposable fixture root
			t.Fatal(err)
		}
	}
	scratch := t.TempDir()
	symdesk := processFixtureBinary(t)
	symroom := filepath.Join(scratch, "symroom")
	build := exec.Command("go", "build", "-o", symroom, "../symroom") //nolint:gosec // fixed Go build of the sibling command
	build.Env = processFixtureBuild.environment
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build Go symroom: %v\n%s", err, output)
	}
	contactsBinary := filepath.Join(scratch, "contacts.test")
	compile := exec.Command("go", "test", "-c", "-o", contactsBinary, "../../internal/contacts") //nolint:gosec // fixed Go build of the contacts seed test
	compile.Env = processFixtureBuild.environment
	if output, err := compile.CombinedOutput(); err != nil {
		t.Fatalf("compile Go contacts seed: %v\n%s", err, output)
	}

	manifest := cutoverManifest{
		SchemaVersion: cutoverSchema,
		GeneratedOn:   cutoverPlatform{GOOS: runtime.GOOS, GOARCH: runtime.GOARCH, GoVersion: runtime.Version()},
		Root:          root,
		Env:           cutoverEnv(root),
		Vars:          map[string]string{},
	}
	runner := &cutoverRunner{t: t, root: root, env: manifest.Env, vars: manifest.Vars,
		binaries: map[string]string{"symdesk": symdesk, "symroom": symroom}}

	write := func(relative, content string) {
		target := filepath.Join(root, filepath.FromSlash(relative))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil { //nolint:gosec // disposable fixture root
			t.Fatal(err)
		}
		if err := os.WriteFile(target, []byte(content), 0o644); err != nil { //nolint:gosec // fixture vault content
			t.Fatal(err)
		}
	}
	write("vault/notes/alpha.md", "---\ntitle: Alpha\ntags: [work, project]\nstatus: open\n---\n# Alpha\nHello [[Beta]] world about kangaroos.\n")
	write("vault/notes/beta.md", "---\ntitle: Beta\ntags: [work]\nstatus: done\n---\n# Beta\nLinks back to [[Alpha]]. Cheese pasta recipe with Müller äöü.\n")
	write("vault/notes/nested/gamma.md", "# Gamma\n\nNo frontmatter, only a [[notes/alpha]] link.\n")
	write("inbox/second.md", "# Second document\n\nAxolotls regenerate limbs.\n")
	write("inbox/report.md", "# Quarterly report\n\nInvoice 4711 from Acme GmbH, total EUR 120.50, due 2026-12-01.\nSecond paragraph about wombats.\n")
	// Pin the retrieval embedding endpoint to a closed loopback port. The
	// default (localhost:11434) reaches whatever Ollama the host happens to
	// run, which made the recorded index and search outputs depend on the
	// recording host and broke the replay on any host without that model.
	write("home/.config/symseek/config.toml", "ollama_url = \"http://127.0.0.1:9/api/embeddings\"\n")

	runner.mustRun("symdesk", "cwd", "--vault", "$ROOT/vault", "index")
	runner.mustRun("symdesk", "cwd", "--vault", "$ROOT/vault", "views", "base", "new", "Tasks", "My tasks")
	runner.mustRun("symdesk", "cwd", "--vault", "$ROOT/vault", "views", "save",
		`{"id":"open-notes","name":"Open notes","source":"tag:work","columns":["title","status"]}`)
	runner.mustRun("symdesk", "cwd", "--vault", "$ROOT/vault", "ingest", "$ROOT/inbox/report.md")

	// Contacts: the domain services are internal to internal/contacts, so the
	// seed is a compiled test of that package run in the recorder's sandbox.
	idsPath := filepath.Join(scratch, "contact-ids.json")
	seed := exec.Command(contactsBinary, "-test.run", "^TestPortCutoverContactsSeed$", "-test.count=1") //nolint:gosec // test binary built above
	seed.Dir = filepath.Join(root, "cwd")
	seed.Env = append(runner.environ(), "PORT_CUTOVER_CONTACTS_OUT="+idsPath)
	if output, err := seed.CombinedOutput(); err != nil {
		t.Fatalf("seed Go contacts: %v\n%s", err, output)
	}
	encodedIDs, err := os.ReadFile(idsPath) //nolint:gosec // recorder scratch file
	if err != nil {
		t.Fatal(err)
	}
	var ids map[string]string
	if err := json.Unmarshal(encodedIDs, &ids); err != nil {
		t.Fatal(err)
	}
	manifest.Vars["ADA"], manifest.Vars["GRACE"], manifest.Vars["ACME"] = ids["ada"], ids["grace"], ids["acme"]
	if manifest.Vars["ADA"] == "" || manifest.Vars["ACME"] == "" {
		t.Fatalf("contact seed returned no ids: %s", encodedIDs)
	}

	// Room: two identities, a signed journal, a second member authoring too.
	runner.mustRun("symroom", "room", "identity", "create", "owner")
	runner.mustRun("symroom", "room", "identity", "create", "bob")
	runner.mustRun("symroom", "room", "init", "--identity", "owner", "--name", "Cutover Room")
	runner.mustRun("symroom", "room", "note", "--identity", "owner", "First note")
	runner.mustRun("symroom", "room", "decide", "--identity", "owner", "Adopt Rust")
	bobShow := runner.mustRun("symroom", "room", "identity", "show", "bob")
	for _, line := range strings.Split(bobShow, "\n") {
		if value, ok := strings.CutPrefix(line, "Member ID: "); ok {
			manifest.Vars["BOB"] = strings.TrimSpace(value)
		}
		if value, ok := strings.CutPrefix(line, "Public Key: "); ok {
			manifest.Vars["BOBKEY"] = strings.TrimSpace(value)
		}
	}
	if manifest.Vars["BOB"] == "" || manifest.Vars["BOBKEY"] == "" {
		t.Fatalf("symroom identity show bob returned no member id: %q", bobShow)
	}
	runner.mustRun("symroom", "room", "member", "add", "--identity", "owner", "--kind", "human", "Bob", manifest.Vars["BOBKEY"])
	runner.mustRun("symroom", "room", "note", "--identity", "bob", "Bob was here")

	queries := cutoverQueries()
	observe := func() []cutoverQuery {
		observed := make([]cutoverQuery, len(queries))
		for i, query := range queries {
			code, stdout, stderr := runner.run(query.Tool, query.Cwd, query.Args, "")
			query.ExitCode, query.Stdout, query.Stderr = code, cutoverNormalize(stdout), cutoverNormalize(stderr)
			observed[i] = query
		}
		return observed
	}

	fixtureDir := cutoverFixtureDirPath(t)
	if err := os.MkdirAll(fixtureDir, 0o755); err != nil { //nolint:gosec // repository fixture directory
		t.Fatal(err)
	}
	snapshot := func(name, description string) cutoverState {
		archiveName := fmt.Sprintf("state-v1-%s-%s.cxa", runtime.GOOS, name)
		digest := cutoverWriteArchive(t, root, filepath.Join(fixtureDir, archiveName))
		return cutoverState{Name: name, Description: description, Archive: archiveName, ArchiveSHA256: digest,
			Files: cutoverScan(t, root), Writes: cutoverWrites()}
	}

	// State 1: exactly what the Go commands left behind, before any read.
	unmigrated := snapshot("unmigrated", "tree as the Go commands left it, before the first read; the first Go read lazily copies the shared retrieval index into the per-vault location")
	unmigrated.Queries = observe()
	unmigrated.AfterReads = cutoverMarkProducts(unmigrated.Files, cutoverScan(t, root))

	// State 2: the same tree after one full Go read pass, i.e. steady state.
	settled := snapshot("settled", "steady state after one Go read pass; further Go reads must leave the tree unchanged")
	settled.Queries = observe()
	settled.AfterReads = cutoverScan(t, root)
	if problems := cutoverDiff(settled.Files, settled.AfterReads); len(problems) != 0 {
		t.Fatalf("Go reads rewrote the settled tree:\n%s", strings.Join(problems, "\n"))
	}
	for i := range settled.Queries {
		if settled.Queries[i].Stdout != unmigrated.Queries[i].Stdout || settled.Queries[i].ExitCode != unmigrated.Queries[i].ExitCode {
			unmigrated.Notes = append(unmigrated.Notes, "first-read output differs from steady state: "+settled.Queries[i].Name)
		}
	}
	manifest.States = []cutoverState{unmigrated, settled}
	return manifest
}

func cutoverFixtureDirPath(t *testing.T) string {
	t.Helper()
	_, source, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("source path unavailable")
	}
	return filepath.Join(filepath.Dir(source), cutoverFixtureDir)
}

func cutoverManifestPath(t *testing.T) string {
	return filepath.Join(cutoverFixtureDirPath(t), fmt.Sprintf("state-v1-%s.json", runtime.GOOS))
}

func TestPortCutoverStateContract(t *testing.T) {
	if os.Getenv("PORT_GENERATE") == "1" {
		manifest := cutoverRecordStates(t)
		encoded, err := json.MarshalIndent(manifest, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(cutoverManifestPath(t), append(encoded, '\n'), 0o644); err != nil { //nolint:gosec // repository fixture
			t.Fatal(err)
		}
		return
	}
	checkCutoverState(t)
}

// checkCutoverState replays the committed tree through the Go binaries: the
// recorded outputs and the post-read tree must still be what Go produces, so
// the Rust replay compares against a live-verified oracle recording.
func checkCutoverState(t *testing.T) {
	t.Helper()
	encoded, err := os.ReadFile(cutoverManifestPath(t)) //nolint:gosec // committed fixture
	if err != nil {
		t.Fatalf("no committed cutover-state fixture for %s: %v", runtime.GOOS, err)
	}
	var manifest cutoverManifest
	if err := json.Unmarshal(encoded, &manifest); err != nil {
		t.Fatal(err)
	}
	root := cutoverCanonicalRoot(t)
	if manifest.Root != root {
		t.Fatalf("fixture was recorded at %s but this host resolves the fixed root to %s", manifest.Root, root)
	}
	scratch := t.TempDir()
	symroom := filepath.Join(scratch, "symroom")
	build := exec.Command("go", "build", "-o", symroom, "../symroom") //nolint:gosec // fixed Go build of the sibling command
	build.Env = processFixtureBuild.environment
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build Go symroom: %v\n%s", err, output)
	}
	runner := &cutoverRunner{t: t, root: root, env: manifest.Env, vars: manifest.Vars,
		binaries: map[string]string{"symdesk": processFixtureBinary(t), "symroom": symroom}}
	for _, state := range manifest.States {
		archive := filepath.Join(cutoverFixtureDirPath(t), state.Archive)
		raw, err := os.ReadFile(archive) //nolint:gosec // committed fixture
		if err != nil {
			t.Fatal(err)
		}
		if sum := sha256.Sum256(raw); hex.EncodeToString(sum[:]) != state.ArchiveSHA256 {
			t.Fatalf("%s: archive digest drifted", state.Name)
		}
		cutoverUnpack(t, archive, root)
		if problems := cutoverDiff(state.Files, cutoverScan(t, root)); len(problems) != 0 {
			t.Fatalf("%s: unpacked tree differs from its manifest:\n%s", state.Name, strings.Join(problems, "\n"))
		}
		for _, query := range state.Queries {
			code, stdout, stderr := runner.run(query.Tool, query.Cwd, query.Args, "")
			if code != query.ExitCode || cutoverNormalize(stdout) != query.Stdout || cutoverNormalize(stderr) != query.Stderr {
				t.Errorf("%s/%s: Go output drifted from the recording (exit %d want %d)\nstdout: %q\nwant:   %q\nstderr: %q\nwant:   %q",
					state.Name, query.Name, code, query.ExitCode, cutoverNormalize(stdout), query.Stdout, cutoverNormalize(stderr), query.Stderr)
			}
		}
		if problems := cutoverDiff(state.AfterReads, cutoverScan(t, root)); len(problems) != 0 {
			t.Errorf("%s: Go reads left a different tree than recorded:\n%s", state.Name, strings.Join(problems, "\n"))
		}
	}
}
