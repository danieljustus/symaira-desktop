//! Port of `internal/draw/emit/typst.go`: Typst markup for the scene graph.
//! Only rectangles, circles and text are emitted (Go's type switch ignores
//! every other primitive, groups included).

use super::emit::number as format_float;
use super::scene::{Primitive, Scene};

/// Go `escapeTypst`.
fn escape_typst(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('[', "\\[")
        .replace(']', "\\]")
        .replace('$', "\\$")
        .replace('#', "\\#")
}

fn rgb(c: &str) -> String {
    format!("rgb(\"{c}\")")
}

fn fill_or_none(fill: &str) -> String {
    if !fill.is_empty() && fill != "none" {
        rgb(fill)
    } else {
        "none".to_owned()
    }
}

fn stroke_or_none(stroke: &str, width: f64) -> String {
    if !stroke.is_empty() && stroke != "none" && width > 0.0 {
        format!("{}pt + {}", format_float(width), rgb(stroke))
    } else {
        "none".to_owned()
    }
}

/// Go `emit.EmitTypst`.
pub fn emit_typst(sc: Option<&Scene>) -> Result<String, String> {
    let sc = sc.ok_or_else(|| "scene is nil".to_owned())?;
    let mut sb = String::new();
    sb.push_str("// Generated by SymDraw\n");
    sb.push_str(&format!(
        "#box(width: {}pt, height: {}pt, {{\n",
        format_float(sc.width),
        format_float(sc.height)
    ));
    if !sc.background.is_empty() && sc.background != "none" && sc.background != "transparent" {
        sb.push_str(&format!(
            "  place(top + left, dx: 0pt, dy: 0pt, rect(width: 100%, height: 100%, fill: rgb(\"{}\")))\n",
            sc.background
        ));
    }
    for p in &sc.primitives {
        match p {
            Primitive::Rect(el) => sb.push_str(&format!(
                "  place(top + left, dx: {}pt, dy: {}pt, rect(width: {}pt, height: {}pt, radius: {}pt, fill: {}, stroke: {}))\n",
                format_float(el.x),
                format_float(el.y),
                format_float(el.width),
                format_float(el.height),
                format_float(el.rx),
                fill_or_none(&el.fill),
                stroke_or_none(&el.stroke, el.stroke_width)
            )),
            Primitive::Circle(el) => sb.push_str(&format!(
                "  place(top + left, dx: {}pt, dy: {}pt, circle(radius: {}pt, fill: {}, stroke: {}))\n",
                format_float(el.cx - el.r),
                format_float(el.cy - el.r),
                format_float(el.r),
                fill_or_none(&el.fill),
                stroke_or_none(&el.stroke, el.stroke_width)
            )),
            Primitive::Text(el) => {
                let fill = if el.fill.is_empty() {
                    "black".to_owned()
                } else {
                    rgb(&el.fill)
                };
                let mut font_size = el.font_size;
                if font_size <= 0.0 {
                    font_size = 14.0;
                }
                sb.push_str(&format!(
                    "  place(top + left, dx: {}pt, dy: {}pt, text(font: \"Inter\", size: {}pt, fill: {}, [{}]))\n",
                    format_float(el.x),
                    format_float(el.y - font_size),
                    format_float(font_size),
                    fill,
                    escape_typst(&el.text)
                ));
            }
            _ => {}
        }
    }
    sb.push_str("})\n");
    Ok(sb)
}
