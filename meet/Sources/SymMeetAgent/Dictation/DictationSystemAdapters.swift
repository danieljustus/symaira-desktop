// MARK: - Pasteboard

/// The general pasteboard behind `DictationPasteboard`.
@MainActor
final class SystemDictationPasteboard: DictationPasteboard {
  private let pasteboard: NSPasteboard

  init(pasteboard: NSPasteboard = .general) {
    self.pasteboard = pasteboard
  }

  var changeCount: Int { pasteboard.changeCount }

  func snapshot() -> ClipboardSnapshot {
    let items = (pasteboard.pasteboardItems ?? []).map { item -> [String: Data] in
      var entry: [String: Data] = [:]
      for type in item.types {
        if let data = item.data(forType: type) { entry[type.rawValue] = data }
      }
      return entry
    }
    return ClipboardSnapshot(items: items)
  }

  func write(text: String) -> Int {
    pasteboard.clearContents()
    let item = NSPasteboardItem()
    item.setString(text, forType: .string)
    // Tell clipboard managers this is a transient value that should not be kept in history.
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
    pasteboard.writeObjects([item])
    return pasteboard.changeCount
  }

  func restore(_ snapshot: ClipboardSnapshot) {
    pasteboard.clearContents()
    let items = snapshot.items.map { entry -> NSPasteboardItem in
      let item = NSPasteboardItem()
      for (type, data) in entry {
        item.setData(data, forType: NSPasteboard.PasteboardType(type))
      }
      return item
    }
    if !items.isEmpty { pasteboard.writeObjects(items) }
  }
}

// MARK: - Keyboard

enum DictationKeyboardError: Error {
  case eventCreationFailed
}

/// Posts Cmd+V or unicode key events with CGEvent. Needs the Accessibility permission.
@MainActor
final class CGEventDictationKeyboard: DictationKeyboard {
  private let source = CGEventSource(stateID: .combinedSessionState)

  func postPaste() throws {
    guard
      let down = CGEvent(
        keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true),
      let up = CGEvent(
        keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
    else { throw DictationKeyboardError.eventCreationFailed }
    // Only Command: the dictation key (Fn) may still be physically down.
    down.flags = .maskCommand
    up.flags = .maskCommand
    down.post(tap: .cgSessionEventTap)
    up.post(tap: .cgSessionEventTap)
  }

  func type(_ text: String) throws {
    let units = Array(text.utf16)
    var index = 0
    // CGEvent carries at most 20 UTF-16 units per event; never split a surrogate pair.
    while index < units.count {
      var end = min(index + 20, units.count)
      if end < units.count, UTF16.isLeadSurrogate(units[end - 1]) { end -= 1 }
      let chunk = Array(units[index..<end])
      guard
        let down = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
        let up = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false)
      else { throw DictationKeyboardError.eventCreationFailed }
      down.flags = []
      up.flags = []
      down.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
      up.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
      down.post(tap: .cgSessionEventTap)
      up.post(tap: .cgSessionEventTap)
      index = end
    }
  }
}

// MARK: - Environment

/// Observes the frontmost application, the focused control and system input state.
@MainActor
final class SystemDictationEnvironment: DictationEnvironment {
  /// Roles that definitely cannot take typed text.
  private static let nonTextRoles: Set<String> = [
    "AXButton", "AXCheckBox", "AXRadioButton", "AXMenuItem", "AXMenuButton", "AXMenuBarItem",
    "AXPopUpButton", "AXImage", "AXStaticText", "AXTabGroup", "AXToolbar", "AXOutline",
    "AXTable", "AXList", "AXRow", "AXCell", "AXColumn", "AXSlider", "AXScrollBar",
    "AXDisclosureTriangle", "AXDock", "AXDockItem",
  ]
  private static let textRoles: Set<String> = [
    "AXTextField", "AXTextArea", "AXComboBox", "AXSearchField",
  ]

  private var electronCache: [String: Bool] = [:]

  func currentConditions() -> InsertionConditions {
    InsertionConditions(
      secureInputActive: IsSecureEventInputEnabled(),
      accessibilityTrusted: AXIsProcessTrusted())
  }

  func currentContext() -> DictationContext {
    DictationContext(appBundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
  }

  func currentTarget() -> InsertionTarget {
    guard let app = NSWorkspace.shared.frontmostApplication else { return InsertionTarget() }
    let bundleID = app.bundleIdentifier
    let electron = isElectron(app)
    let webEngine = electron || InsertionPolicy.chromiumBundleIDs.contains(bundleID ?? "")
    return InsertionTarget(
      bundleID: bundleID,
      isElectronApp: electron,
      focus: focusState(webContentApp: webEngine),
      documentID: "pid:\(app.processIdentifier)")
  }

  private func isElectron(_ app: NSRunningApplication) -> Bool {
    guard let bundleURL = app.bundleURL else { return false }
    let key = bundleURL.path
    if let cached = electronCache[key] { return cached }
    let framework = bundleURL.appending(
      path: "Contents/Frameworks/Electron Framework.framework", directoryHint: .isDirectory)
    let result = FileManager.default.fileExists(atPath: framework.path)
    electronCache[key] = result
    return result
  }

  /// Asks Accessibility what has focus. Chromium and Electron expose web content lazily, so
  /// for them every doubtful answer is `.unknown` (attempt insertion) instead of
  /// `.notTextInput` (hold the text in a card).
  private func focusState(webContentApp: Bool) -> FocusedElementState {
    guard AXIsProcessTrusted() else { return .unknown }
    let system = AXUIElementCreateSystemWide()
    var focused: CFTypeRef?
    let error = AXUIElementCopyAttributeValue(
      system, kAXFocusedUIElementAttribute as CFString, &focused)
    guard error == .success, let focused else {
      return error == .noValue && !webContentApp ? .notTextInput : .unknown
    }
    let element = focused as! AXUIElement  // CFTypeRef of AXUIElement; checked by the call above

    var roleValue: CFTypeRef?
    AXUIElementCopyAttributeValue(element, kAXRoleAttribute as CFString, &roleValue)
    let role = roleValue as? String ?? ""
    if Self.textRoles.contains(role) { return .textInput }

    var settable: DarwinBoolean = false
    if AXUIElementIsAttributeSettable(
      element, kAXSelectedTextRangeAttribute as CFString, &settable) == .success, settable.boolValue
    {
      return .textInput
    }
    if !webContentApp, Self.nonTextRoles.contains(role) { return .notTextInput }
    return .unknown
  }
}
