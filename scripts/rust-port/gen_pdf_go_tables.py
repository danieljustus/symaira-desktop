#!/usr/bin/env python3
"""Regenerate crates/symdesk-index/src/pdf_go_tables.rs from the pinned
github.com/ledongthuc/pdf sources (text.go encodings, name.go glyph names).

    python3 scripts/rust-port/gen_pdf_go_tables.py <ledongthuc-pdf-module-dir>

The module directory is the one `go list -m -f '{{.Dir}}' github.com/ledongthuc/pdf`
prints (revision 5959a4027728). The output is checked in; this script exists
so the tables stay derivable from the Go oracle instead of hand copied.
"""
import re
import sys
from pathlib import Path

REPLACEMENT = 0xFFFD


def encoding_table(source: str, name: str) -> list[int]:
    match = re.search(r"var %s = \[256\]rune\{(.*?)\n\}" % name, source, re.S)
    if not match:
        raise SystemExit(f"{name} not found")
    values = []
    for token in re.findall(r"noRune|0x[0-9a-fA-F]+", match.group(1)):
        values.append(REPLACEMENT if token == "noRune" else int(token, 16))
    if len(values) != 256:
        raise SystemExit(f"{name}: {len(values)} entries")
    return values


def main() -> None:
    module = Path(sys.argv[1])
    text = (module / "text.go").read_text()
    names = (module / "name.go").read_text()
    out = ["//! Generated by scripts/rust-port/gen_pdf_go_tables.py from",
           "//! github.com/ledongthuc/pdf@5959a4027728 (text.go, name.go). Do not edit.",
           ""]
    for rust, go in (("PDF_DOC", "pdfDocEncoding"), ("WIN_ANSI", "winAnsiEncoding"), ("MAC_ROMAN", "macRomanEncoding")):
        table = encoding_table(text, go)
        out.append(f"pub(super) const {rust}: [u32; 256] = [")
        for i in range(0, 256, 8):
            out.append("    " + ", ".join(f"0x{v:04X}" for v in table[i:i + 8]) + ",")
        out.append("];")
        out.append("")
    entries = re.findall(r'^\s*"([^"]+)":\s*(0x[0-9a-fA-F]+),', names, re.M)
    seen = {}
    for glyph, value in entries:
        if glyph in seen:
            raise SystemExit(f"duplicate glyph {glyph}")
        seen[glyph] = int(value, 16)
    out.append("/// Go's `nameToRune`, sorted by glyph name for binary search.")
    out.append(f"pub(super) static NAME_TO_RUNE: [(&str, u32); {len(seen)}] = [")
    for glyph in sorted(seen, key=lambda g: g.encode()):
        out.append(f'    ("{glyph}", 0x{seen[glyph]:04X}),')
    out.append("];")
    out.append("")
    Path("crates/symdesk-index/src/pdf_go_tables.rs").write_text("\n".join(out))


if __name__ == "__main__":
    main()
