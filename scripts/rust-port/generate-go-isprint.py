#!/usr/bin/env python3
"""Translate Go 1.26.10 strconv print tables (not fixture payloads)."""
import argparse
from pathlib import Path
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("goroot", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
assert args.goroot.joinpath("VERSION").read_text().splitlines()[0] == "go1.26.10"
source = args.goroot.joinpath("src/strconv/isprint.go").read_text()
text = '''// Copyright 2013 The Go Authors. All rights reserved.
// Derived from Go 1.26.10 src/strconv/isprint.go and quote.go.
// BSD-3-Clause license: see go-isprint.LICENSE.
// Generated by scripts/rust-port/generate-go-isprint.py; DO NOT EDIT tables.
#![deny(unsafe_code)]

pub(crate) fn is_print(ch: char) -> bool {
    let r = u32::from(ch);
    if r <= 0xff {
        return (0x20..=0x7e).contains(&r) || ((0xa1..=0xff).contains(&r) && r != 0xad);
    }
    let (ranges, exceptions, value) = if r < 0x10000 {
        (IS_PRINT_16, IS_NOT_PRINT_16, r)
    } else {
        (IS_PRINT_32, IS_NOT_PRINT_32, r - 0x10000)
    };
    let i = ranges.partition_point(|&v| v < r);
    i < ranges.len()
        && ranges[i & !1] <= r
        && r <= ranges[i | 1]
        && (r >= 0x20000 || exceptions.binary_search(&value).is_err())
}

'''
for go, rust in [("isPrint16", "IS_PRINT_16"), ("isNotPrint16", "IS_NOT_PRINT_16"), ("isPrint32", "IS_PRINT_32"), ("isNotPrint32", "IS_NOT_PRINT_32")]:
    match = re.search(r"var " + go + r" = \[\]uint(?:16|32)\{([^}]+)\}", source)
    assert match is not None, f"missing Go table: {go}"
    body = match.group(1)
    body = re.sub(r"//[^\n]*", "", body)
    values = re.findall(r"0x[0-9a-f]+", body)
    text += "#[rustfmt::skip]\nconst " + rust + ": &[u32] = &[\n"
    text += "".join("    " + ", ".join(values[i:i+8]) + ",\n" for i in range(0, len(values), 8))
    text += "];\n\n"
root = Path(__file__).resolve().parents[2]
target = root / "crates/symroom-cli/src/go_isprint.rs"
license_target = target.with_name("go-isprint.LICENSE")
license_text = args.goroot.joinpath("LICENSE").read_text()
# Match rustfmt's final trailing-newline policy, keeping table layout stable.
text = text.rstrip() + "\n"
if args.check:
    assert target.read_text() == text, "Go IsPrint table drift"
    assert license_target.read_text() == license_text, "Go license drift"
else:
    target.write_text(text)
    license_target.write_text(license_text)
