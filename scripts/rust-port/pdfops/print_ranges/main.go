// Command print_ranges emits the pinned Go printable-rune table for PDF errors.
// Check mode is read-only and is run by the owning renderer differential.
package main

import (
	"flag"
	"fmt"
	"os"
	"runtime"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	check := flag.Bool("check", false, "compare the committed table without writing")
	flag.Parse()
	if runtime.Version() != "go1.26.10" || unicode.Version != "15.0.0" {
		panic("PDF quoting requires Go 1.26.10 with Unicode 15.0.0")
	}
	var out strings.Builder
	out.WriteString("// Generated by scripts/rust-port/pdfops/print_ranges using Go 1.26.10.\n")
	out.WriteString("// Unicode 15.0 strconv.IsPrint, exhaustively checked by render-differential.\n")
	out.WriteString("// Keep this crate independent of the vault and newer Rust Unicode tables.\n\n")
	out.WriteString("pub(super) fn is_print(c: char) -> bool {\n")
	out.WriteString("    let c = c as u32;\n")
	out.WriteString("    let i = PRINTABLE.partition_point(|&(_, end)| end < c);\n")
	out.WriteString("    PRINTABLE.get(i).is_some_and(|&(start, _)| start <= c)\n}\n\n")
	out.WriteString("const PRINTABLE: &[(u32, u32)] = &[\n")
	ranges := 0
	for c := rune(0); c <= unicode.MaxRune; c++ {
		if !strconv.IsPrint(c) {
			continue
		}
		start := c
		for c < unicode.MaxRune && strconv.IsPrint(c+1) {
			c++
		}
		fmt.Fprintf(&out, "    (0x%x, 0x%x),\n", start, c)
		ranges++
	}
	out.WriteString("];\n")
	if *check {
		data, err := os.ReadFile("crates/symdesk-render/src/go_print.rs")
		if err != nil {
			panic(err)
		}
		if string(data) != out.String() {
			panic("PDF Go printable table drift; regenerate explicitly with the pinned compiler")
		}
		fmt.Printf("PASS %d printable ranges, all Unicode code points checked against strconv.IsPrint\n", ranges)
		return
	}
	fmt.Print(out.String())
}
